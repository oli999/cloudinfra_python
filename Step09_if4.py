"""
    디스크 사용률을 입력(조사해서) 받아서 90 이상이면 
    
    "디스크 용량이 부족합니다!"
    
    70 이상이면 

    "디스크 사용량이 높습니다. 확장을 준비하세요"

    그 이외의 경우에는 

    "정상입니다"

    를 출력하는 프로그래밍 해보기 
"""

disk_usage:int = int(input("디스크 사용률을 입력(0-100):"))

# 만일 disk 사용률이 90 이상이면 
if disk_usage >= 90:
    print("디스크 용량이 부족합니다!")
# 그렇지 않고 만일 disk 사용률이 70 이상이면 
elif disk_usage >= 70:
    print("디스크 사용량이 높습니다. 확장을 준비하세요")
# 위가 모두 아닌경우라면 (디폴트 실행 블럭)
else:
    print("정상입니다")